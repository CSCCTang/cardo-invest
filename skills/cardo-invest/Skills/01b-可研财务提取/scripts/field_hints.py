def build_notes():
    """生成「填写说明」工作表的内容行。"""
    lines = [
        ["填写说明"],
        [""],
        ["本表是 CardoInvest 唯一必需输入。01b 已从可研/匡算表预填能抽到的数值，"],
        ["留空的格子是待填项 —— 点格子看批注（填什么、从哪拿、单位）。"],
        ["填写后直接保存；下次运行 01b 时，已填的格子不会被覆盖。"],
        [""],
    ]
    for sheet in ("项目", "工程费", "其他费", "预备费", "建设期利息",
                  "收入", "成本", "资金结构", "可研财务指标"):
        lines.append(["【{}】".format(sheet)])
        lines.append([SHEET_NOTES.get(sheet, "")])
        for label, hint in FIELD_HINTS.get(sheet, []):
            lines.append(["    {}：{}".format(label, hint)])
        lines.append([""])
    lines.append(["金额单位统一为万元；费率/利率/增长率用小数（如 8% 写 0.08）。"])
    lines.append(["本表所有数字只来自项目材料；抽不到就留空，不用行业经验值代替。"])
    return lines
